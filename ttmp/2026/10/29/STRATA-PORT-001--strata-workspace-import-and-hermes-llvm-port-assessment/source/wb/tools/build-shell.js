#!/usr/bin/env node
/* Concatenate src/shell/*.js (in name order) into site/js/app.js and syntax-check the result.
   usage: node tools/build-shell.js */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'src', 'shell');
const out = path.join(root, 'site', 'js', 'app.js');
const parts = fs.readdirSync(dir).filter(f => /^\d+-.*\.js$/.test(f)).sort();
if (!parts.length) { console.error('build-shell: no parts in ' + dir); process.exit(1); }
const head = '/* Strata Workbench: the shell (host, dock, layouts, views, lab: links, presets store).\n   Generated by tools/build-shell.js from src/shell/' + parts.join(', ') + '. Edit those, not this. */\n';
const body = parts.map(f => `/* ---- ${f} ---- */\n` + fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s*$/, '\n')).join('\n');
fs.writeFileSync(out, head + body);
try { execFileSync(process.execPath, ['--check', out], { stdio: 'pipe' }); }
catch (e) { console.error(String(e.stderr || e.message)); process.exit(1); }
console.log(`build-shell: ${parts.length} parts → site/js/app.js (${(fs.statSync(out).size / 1024).toFixed(1)} KiB), syntax ok`);
