#!/usr/bin/env node
/* Measure the running example and write content-src/book/FACTS.md, the numbers the book quotes.
   usage: node tools/facts.js            (rewrites FACTS.md)
   Every number in the book about the running example should come from this file or from a run
   the text describes. */
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('./check-common.js');
const strata = C.loadEngine();
const { g } = strata;

const src = C.read(path.join(C.SRC, 'presets/B-01/program.js'));
const out = [];
const w = (...xs) => out.push(...xs);
const fence = (lang, text) => w('```' + lang, text.replace(/\s+$/, ''), '```', '');

w('# FACTS: the running example, measured', '', `Generated by \`node tools/facts.js\` with engine ${strata.version}. Do not edit by hand; rerun after engine changes.`, '');
w('## Source (preset B-01, program.js)', '');
fence('js', src.split('\n').map((l, i) => `${String(i + 1).padStart(2)}  ${l}`).join('\n'));

const p = g.compile(g.pipeline(), g.source.text(src, { name: 'program.js' }));
const spec = p.run({ mode: 'spec' }), stress = p.run({ mode: 'plan', gc: 'stress' }), alloc = p.run({ mode: 'plan', gc: 'alloc' });
w('## Runs with the default pipeline', '');
w('| mode | outcome | output | steps | collections | objects moved | peak root slots | allocations | calls | jobs |', '|---|---|---|---|---|---|---|---|---|---|');
for (const [name, r] of [['spec', spec], ['plan, gc alloc', alloc], ['plan, gc stress', stress]])
  w(`| ${name} | ${r.outcome.kind} | ${r.output.join(' / ')} | ${r.steps} | ${r.metrics.collections} | ${r.metrics.moved} | ${r.metrics.peakRootSlots || 0} | ${r.metrics.allocations} | ${r.metrics.calls} | ${r.metrics.jobs} |`);
w('', `observe.equal(spec, plan/stress): ${JSON.stringify(g.observe.equal(spec, stress))}`, '');

w('## The program', '');
w(`Functions, main first: ${p.functions().map(f => '`' + f + '`').join(', ')}.`, '');
w('| function | params | blocks | ops (incl. terminators) | root slots | frame slots | frame bytes | peak live | safepoints |', '|---|---|---|---|---|---|---|---|---|');
for (const f of p.functions()) {
  const fn = p.module.fn(f), pl = p.plan(f);
  w(`| ${f} | ${fn.params.map(x => x.id).join(', ')} | ${fn.blocks.length} | ${fn.blocks.reduce((n, b) => n + b.ops.length + 1, 0)} | ${pl.rootSlots} | ${pl.frameSlots} | ${pl.frameBytes} | ${pl.peakLive} | ${Object.keys(pl.safepoints).length} |`);
}
w('', `metrics(): ${JSON.stringify({ ...p.metrics(), compileMs: undefined })}`, '');
w('Pass trace:', '');
fence('text', p.trace.map(t => `${t.pass.padEnd(14)} ${t.level.padEnd(10)} ${t.note}`).join('\n'));

const byRule = {};
for (const d of p.decisions) { const k = `${d.by} ${d.fired ? 'fired' : 'refused'}`; byRule[k] = (byRule[k] || 0) + 1; }
w('Decisions by rule:', '', ...Object.entries(byRule).map(([k, v]) => `- ${k}: ${v}`), '');
const refused = p.decisions.filter(d => !d.fired).slice(0, 6);
w('First refused decisions:', '', ...refused.map(d => `- ${d.by} at \`${d.at}\` (${d.op}): ${d.because}`), '');

w('## deposit before and after promotion', '');
w('L1.cells (every variable a cell, before promote-cells):', '');
fence('text', p.ir('L1.cells', { fn: 'deposit' }));
w('L1 (after promote-cells and the canonical rewrites):', '');
fence('text', p.ir('L1', { fn: 'deposit' }));
w('L3 (bound to helpers, with the root plan):', '');
fence('text', p.ir('L3', { fn: 'deposit' }));

w('## total: the loop', '');
fence('text', p.ir('L1', { fn: 'total' }));
const f = p.facts('total');
w(`Liveness: ${p.steps('total', 'liveness').length} block visits to the fixed point. Live across each safepoint:`, '');
w(...Object.entries(p.plan('total').safepoints).map(([id, sp]) => `- \`${id}\` ${sp.op}: live ${sp.live.join(', ') || 'nothing'}; required ${sp.required.join(', ') || 'nothing'}; rooted ${sp.rooted.join(', ') || 'nothing'}`), '');
w('Type facts at the loop head (parameters of for1):', '');
const ty = p.facts('total').types;
w(...p.module.fn('total').block('for1').params.map(x => `- ${x.id}: ${ty && ty.typeOf ? ty.typeOf(x.id) : (ty[x.id] || '?')}`), '');
fence('text', p.ir('L3', { fn: 'total' }));

w('## Root strategies on the running example', '');
w('| strategy | ok | root slots (sum) | max frame slots | spec = plan/stress | collections under stress |', '|---|---|---|---|---|---|');
for (const s of ['distinct', 'stackReuse', 'arena', 'none']) {
  const q = g.compile(g.pipeline().roots(s), g.source.text(src));
  const r = q.ok ? q.run({ mode: 'plan', gc: 'stress' }) : null;
  w(`| ${s} | ${q.ok} | ${q.metrics().rootSlots} | ${q.metrics().maxFrameSlots} | ${r ? g.observe.equal(spec, r).equal : 'not compiled: ' + q.diagnostics.filter(d => d.severity === 'error').length + ' missing roots'} | ${r ? r.metrics.collections : '-'} |`);
}
const unchecked = g.compile(g.pipeline().roots('none').checks({ gcSafety: false }), g.source.text(src));
const ur = unchecked.run({ mode: 'plan', gc: 'stress' });
w('', `With roots none and gcSafety off, plan/stress stops: ${ur.outcome.kind}: ${ur.error && ur.error.message}`, '');

w('## Canonical against standard rewrites', '');
const std = g.compile(g.pipeline().rewrites(g.rewrites.standard()), g.source.text(src));
w('| rewrites | ops | rewrites fired | root slots | steps (spec) |', '|---|---|---|---|---|');
for (const [n, q] of [['canonical', p], ['standard', std]]) w(`| ${n} | ${q.metrics().ops} | ${q.metrics().rewritesFired} | ${q.metrics().rootSlots} | ${q.run().steps} |`);
w('');

w('## The throwing getter and naive DCE', '');
const getter = 'const o = { get x() { print("getter ran"); throw new Error("boom"); } };\ntry { const y = o.x; } catch (e) { print("caught " + e.message); }\nprint("end");';
fence('js', getter);
const g1 = g.compile(g.pipeline(), getter), g2 = g.compile(g.pipeline().rewrites(g.rewrites.canonical().with(g.rewrites.naiveDce)), getter);
w(`- canonical: ${g1.run().output.join(' / ')}`, `- canonical + naive-dce: ${g2.run().output.join(' / ') || '(nothing printed)'}`);
const refusal = g1.decisions.find(d => d.by === 'erase-dead-result' && !d.fired);
w(`- erase-dead-result refused at \`${refusal && refusal.at}\`: ${refusal && refusal.because}`);
const law = g.law.refines(g.rewrites.naiveDce, { corpus: [getter] });
w(`- g.law.refines(naiveDce): ok ${law.ok}, before ${JSON.stringify(law.counterexample && law.counterexample.before)}, after ${JSON.stringify(law.counterexample && law.counterexample.after)}`, '');

w('## WebAssembly: a numeric function', '');
const fib = 'function fib(n) {\n  let a = 0, b = 1;\n  for (let i = 0; i < n; i++) { const t = a + b; a = b; b = t; }\n  return a;\n}\nprint(fib(30));';
fence('js', fib);
const wf = g.compile(g.pipeline().assume({ fib: { n: 'number' } }).rewrites(g.rewrites.standard()), fib);
const wr = wf.run({ mode: 'wasm', entry: 'fib', args: [30] });
w(`- with assume fib.n: number and standard rewrites: wasm(fib, 30) = ${wr.outcome.value}; spec = ${wf.run({ entry: 'fib', args: [30] }).outcome.value}; Wasm binary ${wf.wasm().bytes.length} bytes`);
const nf = g.compile(g.pipeline(), fib);
w(`- without the assumption: ${nf.wasm().reasons.fib}`, '');
fence('text', wf.ir('L1', { fn: 'fib' }));

w('## LLVM IR', '');
const ll = p.ir('LLVM');
w(`The module is ${ll.split('\n').length} lines; ${(ll.match(/^declare /gm) || []).length} declarations; ${(ll.match(/^define /gm) || []).length} functions. Structural check: ${p.module.names().map(n => n + ' ' + (p.st.llvm[n].check ? p.st.llvm[n].check.ok : '?')).join(', ')}.`, '');
w('deposit:', '');
fence('llvm', p.ir('LLVM', { fn: 'deposit' }).split('\n').filter(l => !/^declare|^; ModuleID|^target|^;   \d|^; string/.test(l)).join('\n').trim());

w('## Laws', '');
const laws = [g.law.lattice(g.t), g.law.join(), g.law.antitone(), g.law.monotone(g.analysis.liveness), g.law.roundTrip(), g.law.idempotent(), g.law.algebra(g.ops['num.add'], 'associative'), g.law.variant('i32.add', 'num.add')];
w('| law | ok | samples | counterexample |', '|---|---|---|---|');
for (const l of laws) w(`| ${l.name} | ${l.ok} | ${l.samples || ''} | ${l.counterexample ? JSON.stringify(l.counterexample).replace(/\|/g, '\\|').slice(0, 120) : ''} |`);
w('');

w('## Engine', '');
const e = g.engine(); const code = e.admit(p); const ev = e.evaluateScript(code); const jr = e.runJobs();
w(`- admit → code #${code.id}; evaluateScript → ${ev.state}; runJobs → ran ${jr.ran}, remaining ${jr.remaining}; output ${JSON.stringify(e.output())}`);
w(`- metrics: ${JSON.stringify(e.metrics())}`);
w(`- close: ${e.close()}`, '');

fs.writeFileSync(path.join(C.SRC, 'book/FACTS.md'), out.join('\n'));
console.log(`wrote content-src/book/FACTS.md (${out.length} lines)`);
